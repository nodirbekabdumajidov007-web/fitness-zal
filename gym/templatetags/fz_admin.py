@register.simple_tag
def aicon(name, cls=""):
    body = ICONS.get(name) or ICONS["dot"]
    return mark_safe(f'<svg class="ai{" " + cls if cls else ""}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">{body}</svg>')


@register.simple_tag
def model_icon(object_name, cls=""):
    return aicon(MODEL_ICONS.get(str(object_name).lower(), "dot"), cls)


@register.filter
def initials(user):
    """«AK» for Aziz Karimov; falls back to the first letter of the username."""
    a = (getattr(user, "first_name", "") or "")[:1]
    b = (getattr(user, "last_name", "") or "")[:1]
    return (a + b).upper() or (getattr(user, "get_username", lambda: "?")()[:1] or "?").upper()
